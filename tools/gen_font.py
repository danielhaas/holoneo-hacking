#!/usr/bin/env python3
"""Render printable ASCII from a TTF into a 4-bit anti-aliased bitmap font C header.

Usage: gen_font.py FONT.ttf PIXEL_SIZE OUT.h NAME
Each glyph is a fixed cell (W x H); 2 pixels per byte, high nibble first, rows top to bottom.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, size, out, name = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
W = int(round(font.getlength("M")))
H = ascent + descent
W += W % 2  # even width -> whole bytes per row

data = []
for ch in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, 0), chr(ch), font=font, fill=255)
    px = img.load()
    for y in range(H):
        for x in range(0, W, 2):
            hi, lo = px[x, y] >> 4, px[x + 1, y] >> 4
            data.append((hi << 4) | lo)

with open(out, "w") as f:
    f.write(f"// Generated by tools/gen_font.py from {ttf.split('/')[-1]} at {size}px.\n")
    f.write("// Liberation Mono is licensed under the SIL Open Font License 1.1.\n#pragma once\n#include <stdint.h>\n")
    f.write(f"#define {name.upper()}_W {W}\n#define {name.upper()}_H {H}\n")
    f.write(f"static const uint8_t {name}[95 * {W // 2 * H}] = {{\n")
    for i in range(0, len(data), 24):
        f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print(f"{name}: {W}x{H}, {len(data)} bytes")
